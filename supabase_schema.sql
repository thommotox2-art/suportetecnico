-- HABILITAR RLS (Row Level Security) - Exemplo básico permitindo leitura para todos
ALTER TABLE categories ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Leitura pública de categorias" ON categories FOR SELECT USING (true);

ALTER TABLE statuses ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Leitura pública de status" ON statuses FOR SELECT USING (true);

ALTER TABLE tickets ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Usuários veem seus próprios tickets" ON tickets FOR SELECT USING (auth.uid() = user_id OR (SELECT role FROM profiles WHERE id = auth.uid()) = 'admin');
